describe("Inscrição Estadual validation", () => {
  test.each(valids)("the input %p %p should be valid", (uf, value) => {
    expect(isInscricaoEstadual(value, { uf })).toBeTruthy();
  })

  test.each(invalids)("the input %p %p should be invalid", (uf, value) => {
    expect(isInscricaoEstadual(value, { uf })).toBeFalsy();
  })

  test("a valid number checked against the wrong uf should be invalid", () => {
    expect(isInscricaoEstadual('110.042.490.114', { uf: 'SP' })).toBeTruthy();
    expect(isInscricaoEstadual('110.042.490.114', { uf: 'MG' })).toBeFalsy();
    expect(isInscricaoEstadual('062.307.904/0081', { uf: 'SP' })).toBeFalsy();
  })

  test("a number with wrong length should be invalid", () => {
    expect(isInscricaoEstadual('06000001', { uf: 'CE' })).toBeFalsy();
    expect(isInscricaoEstadual('0600000150', { uf: 'CE' })).toBeFalsy();
  })
});
